export function cloneDefaultProgram(): WorkoutDayTemplate[] {
  return JSON.parse(JSON.stringify(DEFAULT_UPPER_LOWER_PROGRAM)) as WorkoutDayTemplate[];
}

export function getWeeklyPlannedMuscleSets(
  program: WorkoutDayTemplate[],
): Record<MuscleGroup, number> {
  const counts: Record<MuscleGroup, number> = {
    peito: 0,
    costas: 0,
    ombros: 0,
    triceps: 0,
    biceps: 0,
    quadriceps: 0,
    posterior: 0,
    gluteos: 0,
    panturrilha: 0,
    abdomen: 0,
    adutores: 0,
  };
  for (const day of program) {
    for (const ex of day.exercises) {
      counts[ex.primaryMuscle] = (counts[ex.primaryMuscle] || 0) + ex.targetSets;
    }
  }
  return counts;
}
